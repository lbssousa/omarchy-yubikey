#!/usr/bin/env python3
"""Build distributable plugin catalogs and the embedded PAM prompt table."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'i18n'
PROMPT = 'Use password fallback? Type password to continue: '


def outputs():
    registry = json.loads((DIRECTORY / 'locales.json').read_text())
    catalogs = {code: json.loads((DIRECTORY / (code + '.json')).read_text()) for code in registry}
    english = catalogs['en']
    prompt_values = [catalog[PROMPT] for catalog in catalogs.values()]
    result = {}
    for role in ['lock', 'polkit']:
        directory = ROOT / 'plugins' / ('yubikey.' + role)
        sources = '\n'.join(p.read_text() for p in directory.glob('*.qml') if p.name != 'Translations.qml')
        keys = set(re.findall(r'strings\.t\("([^"]+)"', sources))
        if role == 'lock':
            keys |= {'Authentication failed (%1)', 'Security key unavailable — retry or use password',
                     'Security key authentication failed — retry or use password'}
        else:
            keys |= {"Authorize running '%1'", 'Enter response'}
        assert keys <= english.keys(), keys - english.keys()
        for code, catalog in catalogs.items():
            result[directory / 'i18n' / (code + '.json')] = json.dumps({key: catalog[key] for key in sorted(keys)}, ensure_ascii=False, indent=2) + '\n'
        result[directory / 'i18n/locales.json'] = (DIRECTORY / 'locales.json').read_text()
        result[directory / 'i18n/fallback-prompts.json'] = json.dumps(prompt_values, ensure_ascii=False, indent=2) + '\n'
        for name in ['Translations.qml', 'Locale.js']:
            result[directory / name] = (DIRECTORY / 'runtime' / name).read_text()
    table = ['/* Generated by scripts/sync-i18n.py; edit the source catalogs in i18n instead. */',
             'struct translated_prompt { const char *code; const char *text; };',
             'static const struct translated_prompt fallback_prompts[] = {']
    for code, catalog in catalogs.items():
        table.append('    {' + json.dumps(code) + ', ' + json.dumps(catalog[PROMPT], ensure_ascii=False) + '},')
    table.append('};\n')
    result[ROOT / 'pam/translations.h'] = '\n'.join(table)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != value:
                raise SystemExit('Outdated generated localization file: ' + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)


if __name__ == '__main__':
    main()
